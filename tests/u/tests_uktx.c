static TestResult test_ktx_read(void) {
	UKtxMemBuffer mem = {
	    .data = s_ktx,
	    .len = sizeof(s_ktx),
	};
	UKtxContext ctx = uktx_openmem(&mem);

	UKtx info = {0};
	UKtxError err = uktx_read(&ctx, &info);
	utassert(err == UKTX_ERR_OK);

	utassert(info.type == UKTX_TYPE_UNSIGNED_BYTE);
	utassert(info.datafmt == UKTX_DFMT_RGB);
	utassert(info.intfmt == UKTX_IFMT_RGB8);
	utassert(info.baseintfmt == UKTX_BIFMT_RGB);
	utassert(info.pixelwidth == 32);
	utassert(info.pixelheight == 32);
	utassert(info.pixeldepth == 0);
	utassert(info.numlevels == 1);
	utassert(info.levels[0].slices[0].faces[0].byteoff == 96);
	utassert(info.levels[0].slices[0].faces[0].bytelen == 3072);

	utassert(info.numkeyvals == 1);
	utassert(info.keyvals[0].keylen == 15);
	utassert(strcmp(info.keyvals[0].key, "KTXorientation") == 0);
	utassert(info.keyvals[0].val_len == 8);
	utassert(strcmp(info.keyvals[0].val, "S=r,T=d") == 0);

	size_t imglen = 0;
	err = uktx_calcimagelen(&info, &imglen, 0);
	utassert(err == UKTX_ERR_OK);
	utassert(imglen == 3072);
	_Static_assert(sizeof(s_ktx) - 96 == 3072, "");

	static uint8_t imgdata[3072] = {0};
	_Static_assert(sizeof(imgdata) == sizeof(s_ktx) - 96, "");
	err = uktx_loadimage(&ctx, &info, imgdata, sizeof(imgdata), 0, 0, 0);
	utassert(memcmp(imgdata, &s_ktx[96], sizeof(s_ktx) - 96) == 0);

	return test_success();
}

