static void writefunc(const void* buf, size_t len, void* userdata) {
	UVec* vec = userdata;
	uvappendmany(vec, buf, len);
}

static TestResult test_ktx_write(void) {
	UVec data = uvalloc(sizeof(uint8_t), 0);

	static const char* key = "KTXorientation";
	static const char* value = "S=r,T=d";
	const UKtxWriteKeyValue keyval = {
	    .key = key,
	    .keylen = strlen(key) + 1,
	    .val = value,
	    .val_len = strlen(value) + 1,
	};
	const UKtxWriteLevel level = {
	    .slices =
		&(UKtxWriteSlice){
		    .faces =
			{
			    {
				.data = &s_ktx[96],
				.len = sizeof(s_ktx) - 96,
			    },
			},
		},
	};
	const UKtxWriteInfo info = {
	    .type = UKTX_TYPE_UNSIGNED_BYTE,
	    .typesize = 1,
	    .datafmt = UKTX_DFMT_RGB,
	    .intfmt = UKTX_IFMT_RGB8,
	    .baseintfmt = UKTX_BIFMT_RGB,
	    .pixelwidth = 32,
	    .pixelheight = 32,
	    .pixeldepth = 0,
	    .numlevels = 1,
	    .numfaces = 1,
	    .numarrayelems = 0,

	    .numkeyvals = 1,
	    .keyvals = &keyval,
	    .levels = &level,
	};
	UKtxError err = uktx_write(writefunc, &data, &info);
	utassert(err == UKTX_ERR_OK);

	utassert(uvbytelen(&data) == sizeof(s_ktx));
	utassert(memcmp(uvdata(&data, 0), s_ktx, sizeof(s_ktx)) == 0);

	uvfree(&data);

	return test_success();
}

