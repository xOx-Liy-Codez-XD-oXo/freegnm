bool runtests_uktx(uint32_t* passedtests) {
	const TestUnit tests[] = {
	    {.fn = &test_ktx_read, .name = "KTX reading RGB8 test"},
	    {.fn = &test_ktx_read_bc3, .name = "KTX reading BC3 test"},
	    {.fn = &test_ktx_write, .name = "KTX writing RGB8 test"},
	    {.fn = &test_ktx_write_bc3, .name = "KTX writing BC3 test"},
	};

	for (size_t i = 0; i < uasize(tests); i += 1) {
		if (!test_run(&tests[i])) {
			return false;
		}
		*passedtests += 1;
	}

	return true;
}
