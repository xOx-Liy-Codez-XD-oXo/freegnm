static TestResult test_dcb_building(void) {
	static uint8_t bufinstance[GNM_INDIRECT_BUFFER_MAX_BYTESIZE] = {0};

	const GnmGpuMode curgpumode = GNM_GPU_BASE;

	// init platform params so WaitUntilSafeForRendering can be issued
	// it gets reset below after the test, just in case
	gnmPlatInit(&(GnmPlatParams){
	    .gpumode = curgpumode,
	    .getbufferlabeladdress = getlabeladdr,
	});

	// fake GPU objects to be used in commands
	const GnmDataFormat colorfmt = GNM_FMT_R8G8B8A8_SRGB;
	const uint32_t colorbpp = gnmDfGetBitsPerElement(colorfmt);
	const uint32_t numfragsperpixel = 1;
	GpaSurfaceProperties surfprops = {0};
	GpaError err = gpaFindOptimalSurface(
	    &surfprops, GPA_SURFACE_COLORDISPLAY, colorbpp, numfragsperpixel,
	    false, curgpumode
	);
	utassert(err == GPA_ERR_OK);

	const GnmRenderTargetCreateInfo rtspec = {
	    .width = 1920,
	    .height = 1080,
	    .pitch = 0,
	    .numslices = 1,

	    .colorfmt = colorfmt,
	    .colortilemodehint = surfprops.tilemode,
	    .mingpumode = curgpumode,
	    .numsamples = 1,
	    .numfragments = 1,
	    .flags = {0},
	};
	GnmRenderTarget fbtarget = {0};
	GnmError gerr = gnmCreateRenderTarget(&fbtarget, &rtspec);
	utassert(gerr == GNM_ERROR_OK);

	gnmRtSetBaseAddr(&fbtarget, (void*)0x34567800);

	const GnmDataFormat depthfmt = gnmDfInitFromZ(GNM_Z_32_FLOAT);
	const GpaTilingParams depthtp = {
	    .tilemode = GNM_TM_DEPTH_2D_THIN_64,
	    .mingpumode = curgpumode,

	    .linearwidth = 1920,
	    .linearheight = 1080,
	    .lineardepth = 1,
	    .numfragsperpixel = 1,
	    .basetiledpitch = 0,

	    .miplevel = 0,
	    .arrayslice = 0,
	    .surfaceflags =
		{
		    .depthtarget = 1,
		    .display = 1,
		},
	    .bitsperfrag = gnmDfGetBitsPerElement(depthfmt),
	    .isblockcompressed = gnmDfIsBlockCompressed(depthfmt),
	};
	GpaSurfaceInfo depthsi = {0};
	err = gpaComputeSurfaceInfo(&depthsi, &depthtp);
	utassert(err == GPA_ERR_OK);

	const GnmDepthRenderTargetCreateInfo depthspec = {
	    .width = depthtp.linearwidth,
	    .height = depthtp.linearheight,
	    .pitch = 0,
	    .numslices = 1,

	    .zfmt = GNM_Z_32_FLOAT,
	    .stencilfmt = GNM_STENCIL_INVALID,
	    .tilemodehint = depthsi.tilemode,
	    .mingpumode = curgpumode,
	    .numfragments = 1,
	};
	GnmDepthRenderTarget depthtarget = {0};
	gerr = gnmCreateDepthRenderTarget(&depthtarget, &depthspec);
	utassert(gerr == GNM_ERROR_OK);

	const GnmVsStageRegisters vsregs = {
	    .spishaderpgmlovs = 0x65432100,
	};
	const GnmPsStageRegisters psregs = {
	    .spishaderpgmlops = 0x21876500,
	};
	const void* indexmem = (void*)0xaabbccddeeff00;
	void* labelmem = (void*)0xeeddccbbaa00;

	const GnmTextureCreateInfo texspec = {
	    .texturetype = GNM_TEXTURE_2D,
	    .width = 32,
	    .height = 32,
	    .depth = 1,
	    .pitch = 32,

	    .nummiplevels = 1,
	    .numslices = 1,

	    .format = GNM_FMT_R8G8B8A8_SRGB,
	    .tilemodehint = GNM_TM_DISPLAY_LINEAR_GENERAL,
	    .mingpumode = GNM_GPU_BASE,
	    .numfragments = 1,
	};
	GnmTexture texture = {0};
	gerr = gnmCreateTexture(&texture, &texspec);
	utassert(gerr == GNM_ERROR_OK);

	const GnmSampler sampler = {
	    .xyminfilter = GNM_FILTER_BILINEAR,
	    .xymagfilter = GNM_FILTER_BILINEAR,
	    .mipfilter = GNM_MIPFILTER_LINEAR,
	    .zfilter = GNM_ZFILTER_POINT,
	    .minlod = 0,
	    .maxlod = 0xfff,
	};

	const GnmBuffer constbuf =
	    gnmCreateConstBuffer((void*)0x2323232345454540, 256);

	// build the command buffer instructions
	GnmCommandBuffer cmdbuf =
	    gnmCmdInit(bufinstance, uasize(bufinstance), NULL, NULL);

	gnmDrawCmdInitDefaultHardwareState(&cmdbuf);

	// test memory alignment
	uint32_t* buf32 =
	    gnmCmdAllocInside(&cmdbuf, sizeof(uint32_t), sizeof(uint32_t));
	utassert(buf32);
	*buf32 = 0xbbccddee;

	uint64_t* buf64 =
	    gnmCmdAllocInside(&cmdbuf, sizeof(uint64_t), sizeof(uint64_t));
	utassert(buf64);
	*buf64 = 0xff11223344556677;

	void* somebuf = gnmCmdAllocInside(&cmdbuf, 0x18, 4);
	memset(somebuf, 0xcc, 0x18);

	gnmDrawCmdWaitUntilSafeForRendering(&cmdbuf, 0x4321, 2);

	gnmDrawCmdSetRenderTarget(&cmdbuf, 0, &fbtarget);
	gnmDrawCmdSetRenderTargetMask(&cmdbuf, 0xf);

	const GnmSetViewportInfo vpinfo = {
	    .dmin = 0.0,
	    .dmax = 1.0,
	    .scale = {1920 * 0.5f, -1080 * 0.5f, 0.5},
	    .offset = {0 + 1920 * 0.5f, 0 + 1080 * 0.5f, 0.5},
	};
	gnmDrawCmdSetViewport(&cmdbuf, 0, &vpinfo);

	const GnmViewportTransformControl vtctrl = {
	    .scalex = true,
	    .offsetx = true,
	    .scaley = true,
	    .offsety = true,
	    .scalez = true,
	    .offsetz = true,
	    .perspectivedividexy = false,
	    .perspectivedividez = false,
	    .invertw = true,
	};
	gnmDrawCmdSetViewportTransformControl(&cmdbuf, &vtctrl);

	gnmDrawCmdSetScreenScissor(&cmdbuf, 0, 0, 1920, 1080);

	const int hwoffsetx = 60;
	const int hwoffsety = 32;
	gnmDrawCmdSetHwScreenOffset(&cmdbuf, hwoffsetx, hwoffsety);

	const float gbhorzclipadjust = 33.133335;
	const float gbvertclipadjust = 59.629631;
	gnmDrawCmdSetGuardBands(
	    &cmdbuf, gbhorzclipadjust, gbvertclipadjust, 1.0f, 1.0f
	);

	gnmDrawCmdSetTsharpUserData(&cmdbuf, GNM_STAGE_PS, 0, &texture);
	gnmDrawCmdSetSsharpUserData(&cmdbuf, GNM_STAGE_PS, 8, &sampler);
	gnmDrawCmdSetVsharpUserData(&cmdbuf, GNM_STAGE_PS, 12, &constbuf);

	gnmDrawCmdSetVsShader(&cmdbuf, &vsregs, 123);
	gnmDrawCmdSetPsShader(&cmdbuf, &psregs);

	const GnmVertexExportSemantic vtxexps[] = {
	    {
		.semantic = 0,
		.outindex = 1,
		.exportf16 = 0x1,
	    },
	    {
		.semantic = 1,
		.outindex = 2,
		.exportf16 = 0,
	    },
	    {
		.semantic = 2,
		.outindex = 3,
		.exportf16 = 0,
	    },
	};
	const GnmPixelInputSemantic psinps[] = {
	    {
		.semantic = 0,
		.interpf16 = 0x1,
		.defaultvalue = GNM_PX_DEFVAL_1_1_1_1,
	    },
	    {
		.semantic = 1,
	    },
	    {
		.semantic = 2,
		.islinear = 1,
		.iscustom = 1,
		.interpf16 = 0x2,
		.defaultvaluehi = GNM_PX_DEFVAL_0_0_0_1,
	    },
	};
	gnmDrawCmdSetPsInputUsage(
	    &cmdbuf, vtxexps, uasize(vtxexps), psinps, uasize(psinps)
	);

	gnmDrawCmdSetEmbeddedVsShader(&cmdbuf, GNM_EMBEDDED_VSH_FULLSCREEN, 0);
	gnmDrawCmdSetEmbeddedPsShader(&cmdbuf, GNM_EMBEDDED_PSH_DUMMY_RG32);

	// setup controls
	const GnmBlendControl blendctrl = {
	    .blendenabled = true,
	    .colorfunc = GNM_COMB_DST_PLUS_SRC,
	    .colorsrcmult = GNM_BLEND_SRC_ALPHA,
	    .colordstmult = GNM_BLEND_ONE_MINUS_SRC_ALPHA,
	    .alphafunc = GNM_COMB_SRC_MINUS_DST,
	    .alphasrcmult = GNM_BLEND_CONSTANT_COLOR,
	    .alphadstmult = GNM_BLEND_ONE_MINUS_CONSTANT_COLOR,
	    .separatealphaenable = true,
	};
	const GnmDbRenderControl dbrenderctrl = {
	    .depthclearenable = false,
	    .stencilclearenable = false,
	    .htileresummarizeenable = false,
	    .depthwritebackpol = false,
	    .stencilwritebackpol = false,
	    .forcedepthdecompress = true,
	    .copycentroidenable = false,
	    .copysampleindex = 0,
	    .copydepthtocolorenable = false,
	    .copystenciltocolorenable = false,
	};
	const GnmDepthStencilControl depthstencilctrl = {
	    .zwrite = true,
	    .zfunc = GNM_DEPTH_COMPARE_GREATEREQUAL,
	    .stencilfunc = GNM_DEPTH_COMPARE_ALWAYS,
	    .stencilbackfunc = GNM_DEPTH_COMPARE_ALWAYS,
	    .separatestencilenable = false,
	    .depthenable = true,
	    .stencilenable = false,
	    .depthboundsenable = false,
	};
	const GnmPrimitiveSetup primsetup = {
	    .cullmode = GNM_CULL_NONE,
	    .frontface = GNM_FACE_CW,
	    .frontmode = GNM_FILL_SOLID,
	    .backmode = GNM_FILL_SOLID,
	    .frontoffsetmode = false,
	    .backoffsetmode = false,
	    .vertexwindowoffsetenable = false,
	    .provokemode = GNM_PROVOKINGVTX_FIRST,
	    .perspectivecorrectiondisable = false,
	};
	gnmDrawCmdSetBlendControl(&cmdbuf, 0, &blendctrl);
	gnmDrawCmdSetDbRenderControl(&cmdbuf, &dbrenderctrl);
	gnmDrawCmdSetDepthStencilControl(&cmdbuf, &depthstencilctrl);
	gnmDrawCmdSetPrimitiveSetup(&cmdbuf, &primsetup);

	gnmDrawCmdSetPrimitiveType(&cmdbuf, GNM_PT_TRILIST);
	gnmDrawCmdSetIndexSize(&cmdbuf, GNM_INDEX_32, GNM_POLICY_LRU);
	gnmDrawCmdDrawIndex(&cmdbuf, 3, indexmem);

	gnmDrawCmdSetPrimitiveType(&cmdbuf, GNM_PT_RECTLIST);
	gnmDrawCmdSetIndexSize(&cmdbuf, GNM_INDEX_16, GNM_POLICY_LRU);
	gnmDrawCmdDrawIndexAuto(&cmdbuf, 3);

	gnmDrawCmdSetInstanceStepRate(&cmdbuf, 4, 2);
	gnmDrawCmdSetNumInstances(&cmdbuf, 50);
	gnmDrawCmdDrawIndex(&cmdbuf, 24, indexmem);

	gnmDrawCmdSetIndirectArgs(&cmdbuf, (void*)0xaaccbbee12345678);
	gnmDrawCmdDrawIndirect(&cmdbuf, 0, GNM_STAGE_ES, 0, 0);

	gnmDrawCmdSetIndexCount(&cmdbuf, 5555);
	gnmDrawCmdSetIndexBuffer(&cmdbuf, (void*)0x123123123ee);
	gnmDrawCmdSetIndexedIndirectArgs(&cmdbuf, (void*)0x12345678aaccbbe8);
	gnmDrawCmdDrawIndexIndirect(&cmdbuf, 0xefd0, GNM_STAGE_VS, 4, 8);

	gnmDrawCmdEventWriteEop(
	    &cmdbuf, GNM_CACHE_FLUSH_TS, (uint64_t)labelmem,
	    GNM_DATA_SEL_SEND_DATA64, 1
	);

	gnmDrawCmdWaitMem(
	    &cmdbuf, GNM_WAIT_REG_MEM_FUNC_EQUAL, (uint64_t)labelmem, 1,
	    0xffffffff
	);
	gnmDrawCmdWaitGraphicsWrite(
	    &cmdbuf, GNM_ACQUIRE_TARGET_CB0 | GNM_ACQUIRE_TARGET_DB
	);

	const uint32_t dcbsize =
	    (cmdbuf.cmdptr - cmdbuf.beginptr) * sizeof(uint32_t);
	utassert(dcbsize == sizeof(s_expecteddcb));
	utassert(memcmp(cmdbuf.beginptr, s_expecteddcb, dcbsize) == 0);

	// reset platform params for other tests
	gnmPlatInit(&(GnmPlatParams){0});

	return test_success();
}

bool runtests_dcb(uint32_t* passedtests) {
	const TestUnit tests[] = {
	    {.fn = &test_dcb_building,
	     .name = "Draw Command Buffer building test"},
	};

	for (uint32_t i = 0; i < uasize(tests); i++) {
		if (!test_run(&tests[i])) {
			return false;
		}
		*passedtests += 1;
	}

	return true;
}
