static TestResult test_gcn_decoder(void) {
	GcnDecoderContext decoder = {0};
	GcnError gerr =
	    gcnDecoderInit(&decoder, s_assembly, sizeof(s_assembly));
	utassert(gerr == GCN_ERR_OK);

	static const GcnMicrocode expectedmicrocodes[] = {
	    GCN_MICROCODE_SOP1, GCN_MICROCODE_VOP3, GCN_MICROCODE_VOP1,
	    GCN_MICROCODE_VOP3, GCN_MICROCODE_VOPC, GCN_MICROCODE_VOP1,
	    GCN_MICROCODE_VOP3, GCN_MICROCODE_VOP3, GCN_MICROCODE_VOP2,
	    GCN_MICROCODE_VOP1, GCN_MICROCODE_VOP1, GCN_MICROCODE_EXP,
	    GCN_MICROCODE_SOPP, GCN_MICROCODE_VOP1, GCN_MICROCODE_VOP3,
	    GCN_MICROCODE_VOP1, GCN_MICROCODE_VOP2, GCN_MICROCODE_EXP,
	    GCN_MICROCODE_SOPP,
	};

	uint32_t curindex = 0;
	while (1) {
		GcnInstruction instr = {0};
		gerr = gcnDecodeInstruction(&decoder, &instr);
		if (gerr == GCN_ERR_END_OF_CODE) {
			break;
		}
		utassert(gerr == GCN_ERR_OK);

		utassert(curindex < uasize(expectedmicrocodes));
		utassert(instr.microcode == expectedmicrocodes[curindex]);

		curindex += 1;
	}

	// reset and disassemble the first instruction again
	gerr = gcnDecoderReset(&decoder);
	utassert(gerr == GCN_ERR_OK);

	GcnInstruction instr = {0};
	gerr = gcnDecodeInstruction(&decoder, &instr);
	utassert(gerr == GCN_ERR_OK);
	utassert(instr.microcode == expectedmicrocodes[0]);

	return test_success();
}

typedef struct {
	uint8_t* buf;
	uint32_t size;
	uint32_t off;
} WriterContext;

static GcnError aswrite(const void* data, uint32_t datasize, void* userdata) {
	WriterContext* w = userdata;
	if (w->off + datasize > w->size) {
		return GCN_ERR_OVERFLOW;
	}
	memcpy(&w->buf[w->off], data, datasize);
	w->off += datasize;
	return GCN_ERR_OK;
}

static TestResult test_gcn_assembler(void) {
	uint8_t shcode[128] = {0};
	WriterContext wctx = {
	    .buf = shcode,
	    .size = sizeof(shcode),
	};
	GcnAssembler as = {
	    .writer = aswrite,
	    .writeuserdata = &wctx,
	};

	GcnError err = gcnAsVop2(
	    &as, GCN_V_MUL_F32, GCN_OPFIELD_VGPR_2, GCN_OPFIELD_SGPR_64,
	    GCN_OPFIELD_VGPR_240
	);
	utassert(err == GCN_ERR_OK);

	err = gcnAsVop2(
	    &as, GCN_V_CVT_PKACCUM_U8_F32, GCN_OPFIELD_VGPR_108,
	    GCN_OPFIELD_EXEC_HI, GCN_OPFIELD_VGPR_53
	);
	utassert(err == GCN_ERR_OK);

	err = gcnAsMubuf(
	    &as, GCN_BUFFER_LOAD_USHORT, GCN_OPFIELD_VGPR_3, GCN_OPFIELD_VGPR_8,
	    GCN_OPFIELD_SGPR_11, GCN_OPFIELD_SGPR_103,
	    &(GcnAsMubufOptions){.idxen = true}
	);
	utassert(err == GCN_ERR_OK);

	err = gcnAsSmrd(
	    &as, GCN_S_BUFFER_LOAD_DWORDX16, GCN_OPFIELD_SGPR_100,
	    GCN_OPFIELD_SGPR_48, 0x14
	);
	utassert(err == GCN_ERR_OK);

	err = gcnAsSop1(
	    &as, GCN_S_SETPC_B64, GCN_OPFIELD_SGPR_0, GCN_OPFIELD_SGPR_30
	);
	utassert(err == GCN_ERR_OK);

	err = gcnAsSopp(&as, GCN_S_WAITCNT, 0x7f);
	utassert(err == GCN_ERR_OK);

	err = gcnAsSopp(&as, GCN_S_ENDPGM, 0);
	utassert(err == GCN_ERR_OK);

	// this one must fail
	err = gcnAsVop2(
	    &as, GCN_V_SUBBREV_U32, GCN_OPFIELD_VCCZ, GCN_OPFIELD_TTMP_2,
	    GCN_OPFIELD_VCC_HI
	);
	utassert(err != GCN_ERR_OK);

	const uint32_t byteswritten = wctx.off;
	utassert(byteswritten == sizeof(s_assembled_data));
	utassert(memcmp(shcode, s_assembled_data, byteswritten) == 0);

	return test_success();
}

static TestResult format_test(
    const void* assembly, size_t assemblysize, const char** expectedinstrs,
    size_t numexpectedinstrs
) {
	GcnDecoderContext decoder = {0};
	GcnError gerr = gcnDecoderInit(&decoder, assembly, assemblysize);
	utassert(gerr == GCN_ERR_OK);

	unsigned i = 0;
	while (1) {
		GcnInstruction instr = {0};
		gerr = gcnDecodeInstruction(&decoder, &instr);
		if (gerr == GCN_ERR_END_OF_CODE) {
			break;
		}
		utassert(gerr == GCN_ERR_OK);

		utassert(i < numexpectedinstrs);

		char strinstr[256] = {0};
		gerr = gcnFormatInstruction(&instr, strinstr, sizeof(strinstr));
		utassert(gerr == GCN_ERR_OK);

		if (strcmp(strinstr, expectedinstrs[i]) != 0) {
			return test_failf(
			    "Instruction \"%s\" does not match expected at %u \"%s\"\n",
			    strinstr, i, expectedinstrs[i]
			);
		}

		i += 1;
	}

	return test_success();
}

