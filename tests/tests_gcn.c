bool runtests_gcn(uint32_t* passedtests) {
	const TestUnit tests[] = {
	    {.fn = &test_gcn_decoder, .name = "GCN decoder test"},
	    {.fn = &test_gcn_assembler, .name = "GCN assembler test"},
	    {.fn = &test_gcn_format_vs, .name = "GCN format VS test"},
	    {.fn = &test_gcn_format_ps, .name = "GCN format PS test"},
	    {.fn = &test_gcn_format_ps2, .name = "GCN format PS test 2"},
	    {.fn = &test_gcn_format_fetch, .name = "GCN format fetch test"},
	    {.fn = &test_gcn_format_embeddedvs,
	     .name = "GCN format embedded VS test"},
	    {.fn = &test_gcn_format_embeddedvs_gpcs4,
	     .name = "GCN format embedded GPCS4 VS test"},
	    {.fn = &test_gcn_format_ps3dpbr, .name = "GCN format PS 3D PBR test"
	    },
	    {.fn = &test_gcn_format_mtbuf, .name = "GCN format MTBUF test"},
	    {.fn = &test_gcn_format_sopc, .name = "GCN format SOPC test"},
	    {.fn = &test_gcn_format_sopk, .name = "GCN format SOPK test"},
	    {.fn = &test_gcn_format_ds, .name = "GCN format DS test"},
	};

	for (size_t i = 0; i < uasize(tests); i++) {
		if (!test_run(&tests[i])) {
			return false;
		}
		*passedtests += 1;
	}

	return true;
}
