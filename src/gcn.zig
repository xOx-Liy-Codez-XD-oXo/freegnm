pub const Decoder = struct {
    ctx: c.GcnDecoderContext,

    pub fn init(gcn_code: []const u32) Decoder {
        var ctx: c.GcnDecoderContext = .{};
        const err = c.gcnDecoderInit(&ctx, @ptrCast(gcn_code.ptr), @intCast(gcn_code.len * @sizeOf(u32)));
        switch (err) {
            c.GCN_ERR_OK => {},
            c.GCN_ERR_CODE_TOO_SMALL => unreachable,
            c.GCN_ERR_INVALID_ARG => unreachable,
            c.GCN_ERR_SIZE_NOT_A_MULTIPLE_FOUR => unreachable,
            else => unreachable,
        }
        return .{
            .ctx = ctx,
        };
    }

    pub fn reset(self: *Decoder) void {
        const err = c.gcnDecoderReset(&self.ctx);
        switch (err) {
            c.GCN_ERR_OK => {},
            c.GCN_ERR_INVALID_ARG => unreachable,
        }
    }

    pub fn getCurrentOffset(self: Decoder) usize {
        return @intFromPtr(self.ctx.curinstr) - @intFromPtr(self.ctx.codestart);
    }

    pub const NextError = error{
        InternalFailure,
        InvalidDestinationField,
        InvalidMicrocode,
        InvalidOpcode,
        InvalidSourceField,
        Unexpected,
        Unimplemented,
    };

    pub fn nextInstruction(self: *Decoder) NextError!?Instruction {
        var instr: Instruction = undefined;
        const err = gcnDecodeInstruction(&self.ctx, &instr);
        switch (err) {
            c.GCN_ERR_OK => {},
            c.GCN_ERR_END_OF_CODE => return null,
            c.GCN_ERR_CODE_TOO_SMALL => unreachable,
            c.GCN_ERR_INVALID_ARG => unreachable,
            c.GCN_ERR_INVALID_DST_FIELD => return error.InvalidDestinationField,
            c.GCN_ERR_INVALID_MICROCODE => return error.InvalidMicrocode,
            c.GCN_ERR_INVALID_OPCODE => return error.InvalidOpcode,
            c.GCN_ERR_INVALID_SRC_FIELD => return error.InvalidSourceField,
            c.GCN_ERR_INTERNAL_ERROR => return error.InternalFailure,
            c.GCN_ERR_UNIMPLEMENTED => return error.Unimplemented,
            c.GCN_ERR_UNINITIALIZED_CONTEXT => unreachable,
            else => return error.Unexpected,
        }
        return instr;
    }
};

extern fn gcnDecodeInstruction(ctx: *c.GcnDecoderContext, out_instr: *Instruction) c.GcnError;
extern fn gcnFormatInstruction(instr: *const Instruction, out_buffer: [*:0]u8, out_buffer_len: usize) c.GcnError;
