static TestResult test_fetchsh_building(void) {
	const uint32_t remapsemantictable[3] = {0, 1, 2};

	const GnmVsShader* vsh = (const GnmVsShader*)s_vshaderdata;
	const GnmFetchShaderCreateInfo ci = {
	    .regs = &vsh->registers,
	    .flags = 0,
	    .vtxinputs = gnmVsShaderInputSemanticTable(vsh),
	    .numvtxinputs = vsh->numinputsemantics,
	    .inputusages = gnmVsShaderInputUsageSlotTable(vsh),
	    .numinputusages = vsh->common.numinputusageslots,
	    .remaptable = remapsemantictable,
	    .remaptablecount = uasize(remapsemantictable),
	    .vertexbaseusgpr = 0,
	    .instancebaseusgpr = 0,
	};
	uint32_t fetchsize = 0;
	GnmError err = gnmFetchShaderCalcSize(&fetchsize, &ci);
	utassert(err == GNM_ERROR_OK);
	utassert(fetchsize == 52);

	uint8_t fsbuf[64] = {0};
	GnmFetchShaderResults res = {0};
	err = gnmCreateFetchShader(fsbuf, sizeof(fsbuf), &ci, &res);
	utassert(err == GNM_ERROR_OK);

	utassert(memcmp(fsbuf, s_fetchdata, fetchsize) == 0);
	utassert(res.sgprs == 2);
	utassert(res.vgprcompcnt == 0);

	return test_success();
}

