bool runtests_fetchsh(uint32_t* passedtests) {
	const TestUnit tests[] = {
	    {.fn = &test_fetchsh_building, .name = "Fetch shader build test"},
	    {.fn = &test_fetchsh_building2, .name = "Fetch shader build test 2"
	    },
	    {.fn = &test_fetchsh_instanced,
	     .name = "Fetch shader instanced test"},
	    {.fn = &test_fetchsh_instanced2,
	     .name = "Fetch shader instanced test 2"},
	};

	for (uint32_t i = 0; i < uasize(tests); i++) {
		if (!test_run(&tests[i])) {
			return false;
		}
		*passedtests += 1;
	}

	return true;
}
