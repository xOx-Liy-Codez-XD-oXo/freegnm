static TestResult test_pssl_sbvalidation(void) {
	PsslError perr =
	    psslValidateShaderBinary(s_vertshader, sizeof(s_vertshader));
	utassert(perr == PSSL_ERR_OK);
	return test_success();
}

static TestResult test_pssl_sbvalues(void) {
	const PsslBinaryHeader* hdr = (const void*)s_vertshader;

	PsslShaderType shtype = hdr->shadertype;
	PsslCodeType codetype = hdr->codetype;
	PsslCompilerType comptype = psslSbCompilerType(hdr);

	utassert(shtype == PSSL_SHADER_VS);
	utassert(codetype == PSSL_CODE_ISA);
	utassert(comptype == PSSL_COMPILER_ORBIS_WAVE);
	utassert(hdr->codesize == 188);

	return test_success();
}

bool runtests_pssl(uint32_t* passedtests) {
	const TestUnit tests[] = {
	    {.fn = &test_pssl_sbvalidation, .name = "PSSL SB validation test"},
	    {.fn = &test_pssl_sbvalues, .name = "PSSL SB values test"},
	};

	for (size_t i = 0; i < uasize(tests); i++) {
		if (!test_run(&tests[i])) {
			return false;
		}
		*passedtests += 1;
	}

	return true;
}
